CREATE FUNCTION public.classification_check_outbox_state()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  v_run_id BIGINT;
  v_run_state TEXT;
  v_outbox_state TEXT;
  v_outbox_lease TIMESTAMPTZ;
  v_expected TEXT;
BEGIN
  IF TG_TABLE_NAME = 'classification_runs' THEN
    v_run_id := NEW.id;
  ELSE
    v_run_id := NEW.run_id;
  END IF;
  SELECT state INTO v_run_state FROM public.classification_runs WHERE id = v_run_id;
  IF NOT FOUND THEN RETURN NULL; END IF;
