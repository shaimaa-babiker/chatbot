-- Worker primitives are durable SQL capabilities only; this migration does
-- not create or imply a deployed worker/scheduler.
CREATE FUNCTION public.claim_classification_run(
  p_fencing_token TEXT,
  p_lease_seconds INTEGER
)
RETURNS TABLE(
  run_id BIGINT, attempt_id BIGINT, fencing_token TEXT, lease_expires_at TIMESTAMPTZ,
  chatbot_id INTEGER, chat_session_id INTEGER, message_id INTEGER,
  taxonomy_version_id BIGINT, operation_identity JSONB
)
LANGUAGE plpgsql AS $$
DECLARE
  v_candidate RECORD;
  v_attempt_id BIGINT;
  v_expiry TIMESTAMPTZ;
BEGIN
  IF p_fencing_token IS NULL OR length(btrim(p_fencing_token)) < 16
     OR p_lease_seconds IS NULL OR p_lease_seconds < 15 OR p_lease_seconds > 3600 THEN
    RAISE EXCEPTION 'Invalid worker lease request';
  END IF;

  SELECT r.id, r.chatbot_id, r.chat_session_id, r.message_id,
         r.taxonomy_version_id, r.operation_identity, r.state,
         r.attempt_count, r.max_attempts, r.next_attempt_at,
         o.id AS outbox_id, o.lease_expires_at AS outbox_lease
    INTO v_candidate
    FROM public.classification_runs r
    JOIN public.classification_outbox o ON o.run_id = r.id
    WHERE (r.state IN ('queued', 'retryable_failed')
           AND o.state = 'ready'
           AND (r.next_attempt_at IS NULL OR r.next_attempt_at <= clock_timestamp())
           AND o.available_at <= clock_timestamp())
       OR (r.state = 'running' AND o.state = 'claimed'
           AND o.lease_expires_at <= clock_timestamp())
    ORDER BY o.available_at, r.created_at, r.id
    LIMIT 1
    FOR UPDATE OF r, o SKIP LOCKED;
  IF NOT FOUND THEN RETURN; END IF;

  IF v_candidate.state = 'running' THEN
    UPDATE public.classification_attempts
      SET state = 'abandoned', lease_expires_at = NULL, completed_at = clock_timestamp()
      WHERE run_id = v_candidate.id AND state = 'running';
  END IF;

  IF v_candidate.attempt_count >= v_candidate.max_attempts THEN
    UPDATE public.classification_runs
      SET state = 'dead_letter', completed_at = clock_timestamp(), next_attempt_at = NULL
      WHERE id = v_candidate.id;
    UPDATE public.classification_outbox
      SET state = 'dead_letter', lease_expires_at = NULL
      WHERE id = v_candidate.outbox_id;
    RETURN;
  END IF;

  v_expiry := clock_timestamp() + make_interval(secs => p_lease_seconds);
  INSERT INTO public.classification_attempts(
    run_id, attempt_number, state, fencing_token, lease_expires_at
  ) VALUES (
    v_candidate.id, v_candidate.attempt_count + 1, 'running', p_fencing_token, v_expiry
  ) RETURNING id INTO v_attempt_id;
  UPDATE public.classification_runs
    SET state = 'running', attempt_count = attempt_count + 1,
        next_attempt_at = NULL, completed_at = NULL
    WHERE id = v_candidate.id;
  UPDATE public.classification_outbox
    SET state = 'claimed', lease_expires_at = v_expiry
    WHERE id = v_candidate.outbox_id;

  RETURN QUERY SELECT v_candidate.id, v_attempt_id, p_fencing_token, v_expiry,
    v_candidate.chatbot_id, v_candidate.chat_session_id, v_candidate.message_id,
    v_candidate.taxonomy_version_id, v_candidate.operation_identity;
END;
$$;

CREATE FUNCTION public.renew_classification_lease(
  p_run_id BIGINT,
  p_attempt_id BIGINT,
  p_fencing_token TEXT,
  p_lease_seconds INTEGER
)
RETURNS TIMESTAMPTZ LANGUAGE plpgsql AS $$
DECLARE
  v_expiry TIMESTAMPTZ;
BEGIN
  IF p_lease_seconds IS NULL OR p_lease_seconds < 15 OR p_lease_seconds > 3600 THEN
    RAISE EXCEPTION 'Invalid lease duration';
  END IF;
  PERFORM 1 FROM public.classification_runs WHERE id = p_run_id AND state = 'running' FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Run is not running'; END IF;
  PERFORM 1 FROM public.classification_attempts
    WHERE id = p_attempt_id AND run_id = p_run_id AND state = 'running'
      AND fencing_token = p_fencing_token AND lease_expires_at > clock_timestamp()
    FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Attempt lease is stale or expired'; END IF;
  v_expiry := clock_timestamp() + make_interval(secs => p_lease_seconds);
  UPDATE public.classification_attempts SET lease_expires_at = v_expiry WHERE id = p_attempt_id;
  UPDATE public.classification_outbox SET lease_expires_at = v_expiry
    WHERE run_id = p_run_id AND state = 'claimed';
  RETURN v_expiry;
END;
$$;

CREATE FUNCTION public.fail_classification_run(
  p_run_id BIGINT,
  p_attempt_id BIGINT,
  p_fencing_token TEXT,
  p_error_code TEXT,
  p_retry_delay_seconds INTEGER DEFAULT 30,
  p_retryable BOOLEAN DEFAULT TRUE
)
RETURNS TEXT LANGUAGE plpgsql AS $$
DECLARE
  v_run public.classification_runs%ROWTYPE;
  v_attempt public.classification_attempts%ROWTYPE;
  v_terminal BOOLEAN;
  v_next_attempt TIMESTAMPTZ;
BEGIN
  SELECT * INTO v_run FROM public.classification_runs WHERE id = p_run_id FOR UPDATE;
  IF NOT FOUND OR v_run.state <> 'running' THEN RAISE EXCEPTION 'Run is not running'; END IF;
  SELECT * INTO v_attempt FROM public.classification_attempts
    WHERE id = p_attempt_id AND run_id = p_run_id FOR UPDATE;
  IF NOT FOUND OR v_attempt.state <> 'running'
     OR v_attempt.fencing_token <> p_fencing_token
     OR v_attempt.lease_expires_at <= clock_timestamp() THEN
    RAISE EXCEPTION 'Attempt lease is stale or expired';
  END IF;
  IF p_retry_delay_seconds < 0 OR p_retry_delay_seconds > 86400 OR p_retryable IS NULL THEN
    RAISE EXCEPTION 'Invalid retry delay';
  END IF;
  v_terminal := NOT p_retryable OR v_run.attempt_count >= v_run.max_attempts;
  v_next_attempt := clock_timestamp() + make_interval(secs => p_retry_delay_seconds);
  UPDATE public.classification_attempts
    SET state = 'failed', lease_expires_at = NULL, completed_at = clock_timestamp(),
        error_code = left(p_error_code, 200)
    WHERE id = p_attempt_id;
  UPDATE public.classification_runs
    SET state = CASE WHEN v_terminal THEN 'dead_letter' ELSE 'retryable_failed' END,
        completed_at = CASE WHEN v_terminal THEN clock_timestamp() ELSE NULL END,
        next_attempt_at = CASE WHEN v_terminal THEN NULL ELSE v_next_attempt END
    WHERE id = p_run_id;
  UPDATE public.classification_outbox
    SET state = CASE WHEN v_terminal THEN 'dead_letter' ELSE 'ready' END,
        available_at = v_next_attempt, lease_expires_at = NULL
    WHERE run_id = p_run_id;
  RETURN CASE WHEN v_terminal THEN 'dead_letter' ELSE 'retryable_failed' END;
END;
$$;

CREATE FUNCTION public.complete_classification_run(
  p_run_id BIGINT,
  p_attempt_id BIGINT,
  p_fencing_token TEXT,
  p_outcome TEXT,
  p_confidence NUMERIC,
  p_labels JSONB,
  p_model_version TEXT,
  p_prompt_version TEXT
)
RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE
  v_run public.classification_runs%ROWTYPE;
  v_attempt public.classification_attempts%ROWTYPE;
  v_decision_id BIGINT;
  v_label JSONB;
  v_category_text TEXT;
  v_category_id BIGINT;
  v_rationale TEXT;
BEGIN
  SELECT * INTO v_run FROM public.classification_runs WHERE id = p_run_id FOR UPDATE;
  IF NOT FOUND OR v_run.state <> 'running' OR v_run.taxonomy_version_id IS NULL THEN
    RAISE EXCEPTION 'Run is not a bound running operation';
  END IF;
  SELECT * INTO v_attempt FROM public.classification_attempts
    WHERE id = p_attempt_id AND run_id = p_run_id FOR UPDATE;
  IF NOT FOUND OR v_attempt.state <> 'running'
     OR v_attempt.fencing_token <> p_fencing_token
     OR v_attempt.lease_expires_at <= clock_timestamp() THEN
    RAISE EXCEPTION 'Attempt lease is stale or expired';
  END IF;
  IF p_outcome IS NULL OR p_outcome NOT IN ('classified', 'uncertain', 'unclassified', 'excluded') THEN
    RAISE EXCEPTION 'Invalid classification outcome';
  END IF;
  IF p_labels IS NULL OR jsonb_typeof(p_labels) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'Labels must be a JSON array';
  END IF;
  IF p_outcome = 'classified' AND jsonb_array_length(p_labels) = 0 THEN
    RAISE EXCEPTION 'Classified outcomes require at least one label';
  END IF;
  IF p_outcome <> 'classified' AND jsonb_array_length(p_labels) <> 0 THEN
    RAISE EXCEPTION 'Only classified outcomes may contain labels';
  END IF;

  INSERT INTO public.classification_decisions(
    run_id, chatbot_id, message_id, taxonomy_version_id, outcome, confidence, provenance
  ) VALUES (
    v_run.id, v_run.chatbot_id, v_run.message_id, v_run.taxonomy_version_id,
    p_outcome, p_confidence, 'ai'
  ) RETURNING id INTO v_decision_id;
  INSERT INTO public.classification_review_state(
    decision_id, chatbot_id, message_id, taxonomy_version_id, state, updated_by
  ) VALUES (
    v_decision_id, v_run.chatbot_id, v_run.message_id, v_run.taxonomy_version_id,
    'pending', 'system:classifier'
  );

  FOR v_label IN SELECT value FROM jsonb_array_elements(p_labels)
  LOOP
    IF jsonb_typeof(v_label) IS DISTINCT FROM 'object' THEN
      RAISE EXCEPTION 'Each label must be an object';
    END IF;
    IF jsonb_object_length(v_label) <> 2
       OR jsonb_typeof(v_label->'rationale') IS DISTINCT FROM 'string'
       OR jsonb_typeof(v_label->'categoryId') NOT IN ('string', 'number') THEN
      RAISE EXCEPTION 'Each label must contain only categoryId and rationale';
    END IF;
    v_category_text := v_label->>'categoryId';
    v_rationale := btrim(COALESCE(v_label->>'rationale', ''));
    IF v_category_text IS NULL OR v_category_text !~ '^[1-9][0-9]*$'
       OR length(v_rationale) = 0 THEN
      RAISE EXCEPTION 'Each label requires a positive categoryId and nonblank rationale';
    END IF;
    v_category_id := v_category_text::BIGINT;
    INSERT INTO public.classification_decision_labels(
      decision_id, chatbot_id, message_id, taxonomy_version_id, category_id, rationale
    ) VALUES (
      v_decision_id, v_run.chatbot_id, v_run.message_id,
      v_run.taxonomy_version_id, v_category_id, v_rationale
    );
  END LOOP;

  UPDATE public.classification_attempts
    SET state = 'succeeded', lease_expires_at = NULL, completed_at = clock_timestamp(),
        model_version = p_model_version, prompt_version = p_prompt_version
    WHERE id = p_attempt_id;
  UPDATE public.classification_runs
    SET state = 'succeeded', completed_at = clock_timestamp(), next_attempt_at = NULL
    WHERE id = p_run_id;
  UPDATE public.classification_outbox
    SET state = 'delivered', lease_expires_at = NULL
    WHERE run_id = p_run_id AND state = 'claimed';
  RETURN v_decision_id;
END;
$$;

-- This invoker-rights routine must only be called after the API has checked
-- that p_actor_user_id owns the chatbot. A supplied actor id is audit data,
-- not authentication; no SECURITY DEFINER or custom GUC is used.
CREATE FUNCTION public.activate_classification_taxonomy(
  p_chatbot_id INTEGER,
  p_version_id BIGINT,
  p_actor_user_id TEXT
)
RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE
  v_state TEXT;
  v_category_count BIGINT;
  v_old_version_id BIGINT;
BEGIN
  PERFORM 1 FROM public.chatbots
    WHERE id = p_chatbot_id AND archived_at IS NULL
    FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Chatbot not found or archived'; END IF;

  SELECT state INTO v_state
    FROM public.classification_taxonomy_versions
    WHERE chatbot_id = p_chatbot_id AND id = p_version_id
    FOR UPDATE;
  IF v_state IS DISTINCT FROM 'approved' THEN
    RAISE EXCEPTION 'Only an approved taxonomy can be activated';
  END IF;
  SELECT count(*) INTO v_category_count
    FROM public.classification_taxonomy_memberships
    WHERE chatbot_id = p_chatbot_id AND taxonomy_version_id = p_version_id;
  IF v_category_count < 1 THEN RAISE EXCEPTION 'Taxonomy must contain a category'; END IF;

  SELECT id INTO v_old_version_id
    FROM public.classification_taxonomy_versions
    WHERE chatbot_id = p_chatbot_id AND state = 'active'
    FOR UPDATE;
  IF v_old_version_id IS NOT NULL THEN
    UPDATE public.classification_taxonomy_versions
      SET state = 'superseded'
      WHERE chatbot_id = p_chatbot_id AND id = v_old_version_id;
    INSERT INTO public.classification_taxonomy_events(chatbot_id, taxonomy_version_id, event_type, actor_user_id)
      VALUES (p_chatbot_id, v_old_version_id, 'superseded', p_actor_user_id);
  END IF;

  UPDATE public.classification_taxonomy_versions
    SET state = 'active', activated_at = now()
    WHERE chatbot_id = p_chatbot_id AND id = p_version_id;
  INSERT INTO public.classification_taxonomy_events(chatbot_id, taxonomy_version_id, event_type, actor_user_id)
    VALUES (p_chatbot_id, p_version_id, 'activated', p_actor_user_id);

  UPDATE public.classification_runs
    SET taxonomy_version_id = p_version_id, state = 'queued'
    WHERE chatbot_id = p_chatbot_id AND state = 'pending_taxonomy';
  UPDATE public.classification_outbox o
    SET state = 'ready', available_at = now()
    FROM public.classification_runs r
    WHERE r.id = o.run_id AND r.chatbot_id = p_chatbot_id
      AND r.taxonomy_version_id = p_version_id AND o.state = 'pending_taxonomy';
END;
$$;

