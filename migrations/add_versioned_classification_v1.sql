CREATE FUNCTION public.classification_guard_review_transition()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Review state cannot be deleted';
  END IF;
  IF (NEW.decision_id, NEW.chatbot_id, NEW.message_id, NEW.taxonomy_version_id)
     IS DISTINCT FROM (OLD.decision_id, OLD.chatbot_id, OLD.message_id, OLD.taxonomy_version_id) THEN
    RAISE EXCEPTION 'Review state identity is immutable';
  END IF;
  IF NOT (
    (OLD.state = 'pending' AND NEW.state IN ('accepted', 'rejected', 'flagged'))
    OR (OLD.state = 'accepted' AND NEW.state IN ('rejected', 'flagged'))
    OR (OLD.state = 'flagged' AND NEW.state IN ('accepted', 'rejected', 'pending'))
