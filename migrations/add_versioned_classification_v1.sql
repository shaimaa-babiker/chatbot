    RAISE EXCEPTION 'Invalid review-state transition';
  END IF;
  IF NEW.state <> 'accepted' AND EXISTS (
    SELECT 1 FROM public.classification_canonical_heads h
    WHERE h.decision_id = NEW.decision_id
  ) THEN
    RAISE EXCEPTION 'Deselect a canonical decision before rejecting or flagging it';
  END IF;
  RETURN NEW;
END;
$$;

