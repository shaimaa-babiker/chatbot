CREATE FUNCTION public.classification_guard_taxonomy_version()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Taxonomy version history cannot be deleted';
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW.state <> 'draft' OR NEW.approved_at IS NOT NULL
       OR NEW.approved_by IS NOT NULL OR NEW.activated_at IS NOT NULL THEN
      RAISE EXCEPTION 'Taxonomy versions start as unapproved drafts';
    END IF;
    RETURN NEW;
  END IF;
  IF (NEW.id, NEW.chatbot_id, NEW.version_number, NEW.created_at)
     IS DISTINCT FROM (OLD.id, OLD.chatbot_id, OLD.version_number, OLD.created_at) THEN
    RAISE EXCEPTION 'Taxonomy version identity is immutable';
  END IF;
  IF NOT (
    (OLD.state = 'draft' AND NEW.state IN ('draft', 'approved'))
    OR (OLD.state = 'approved' AND NEW.state IN ('approved', 'active'))
    OR (OLD.state = 'active' AND NEW.state = 'superseded')
    OR (OLD.state = 'superseded' AND NEW.state IN ('superseded', 'archived'))
    OR (OLD.state = 'archived' AND NEW.state = 'archived')
  ) THEN
    RAISE EXCEPTION 'Invalid taxonomy lifecycle transition';
  END IF;
  IF OLD.state = 'draft' AND NEW.state = 'approved' THEN
    IF NEW.approved_at IS NULL OR NEW.approved_by IS NULL OR NEW.activated_at IS NOT NULL THEN
      RAISE EXCEPTION 'Approval must record reviewer and time only';
    END IF;
  ELSIF OLD.state = 'approved' AND NEW.state = 'active' THEN
    IF NEW.approved_at IS DISTINCT FROM OLD.approved_at
       OR NEW.approved_by IS DISTINCT FROM OLD.approved_by
       OR NEW.activated_at IS NULL THEN
      RAISE EXCEPTION 'Activation must preserve approval and record activation time';
    END IF;
  ELSIF (NEW.approved_at, NEW.approved_by, NEW.activated_at)
        IS DISTINCT FROM (OLD.approved_at, OLD.approved_by, OLD.activated_at) THEN
    RAISE EXCEPTION 'Taxonomy audit fields are immutable outside approval/activation';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER classification_taxonomy_version_guard
  BEFORE INSERT OR UPDATE OR DELETE ON public.classification_taxonomy_versions
  FOR EACH ROW EXECUTE FUNCTION public.classification_guard_taxonomy_version();

CREATE FUNCTION public.classification_guard_taxonomy_membership()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  v_chatbot_id INTEGER;
  v_version_id BIGINT;
  v_state TEXT;
BEGIN
  IF TG_OP = 'UPDATE'
     AND (NEW.chatbot_id, NEW.taxonomy_version_id, NEW.category_id)
         IS DISTINCT FROM (OLD.chatbot_id, OLD.taxonomy_version_id, OLD.category_id) THEN
    RAISE EXCEPTION 'Taxonomy membership identity is immutable';
  END IF;
  IF TG_OP = 'DELETE' THEN
    v_chatbot_id := OLD.chatbot_id;
    v_version_id := OLD.taxonomy_version_id;
  ELSE
    v_chatbot_id := NEW.chatbot_id;
    v_version_id := NEW.taxonomy_version_id;
  END IF;
  SELECT state INTO v_state FROM public.classification_taxonomy_versions
    WHERE chatbot_id = v_chatbot_id AND id = v_version_id FOR UPDATE;
  IF v_state IS DISTINCT FROM 'draft' THEN
    RAISE EXCEPTION 'Only draft taxonomy membership may be changed';
  END IF;
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER classification_taxonomy_membership_guard
  BEFORE INSERT OR UPDATE OR DELETE ON public.classification_taxonomy_memberships
  FOR EACH ROW EXECUTE FUNCTION public.classification_guard_taxonomy_membership();

CREATE FUNCTION public.create_classification_taxonomy_draft(
  p_chatbot_id INTEGER,
  p_actor_user_id TEXT,
  p_categories JSONB
)
RETURNS BIGINT LANGUAGE plpgsql AS $$
DECLARE
  v_version_id BIGINT;
  v_version_number INTEGER;
  v_category JSONB;
  v_category_id BIGINT;
  v_name TEXT;
  v_definition TEXT;
BEGIN
  IF p_actor_user_id IS NULL OR length(btrim(p_actor_user_id)) = 0
     OR p_categories IS NULL OR jsonb_typeof(p_categories) IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'A taxonomy owner and category array are required';
  END IF;
  IF jsonb_array_length(p_categories) = 0 THEN
    RAISE EXCEPTION 'At least one category is required';
  END IF;
  PERFORM 1 FROM public.chatbots
    WHERE id = p_chatbot_id AND archived_at IS NULL FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Chatbot not found or archived'; END IF;
  SELECT COALESCE(max(version_number), 0) + 1 INTO v_version_number
    FROM public.classification_taxonomy_versions WHERE chatbot_id = p_chatbot_id;
  INSERT INTO public.classification_taxonomy_versions(chatbot_id, version_number, state)
    VALUES (p_chatbot_id, v_version_number, 'draft') RETURNING id INTO v_version_id;

  FOR v_category IN SELECT value FROM jsonb_array_elements(p_categories)
  LOOP
    IF jsonb_typeof(v_category) IS DISTINCT FROM 'object' THEN
      RAISE EXCEPTION 'Each taxonomy category must be an object';
    END IF;
    v_name := btrim(COALESCE(v_category->>'name', ''));
    v_definition := btrim(COALESCE(v_category->>'definition', ''));
    IF length(v_name) = 0 OR length(v_name) > 120
       OR length(v_definition) = 0 OR length(v_definition) > 2000 THEN
      RAISE EXCEPTION 'Taxonomy category requires a valid name and definition';
    END IF;
    INSERT INTO public.classification_categories(chatbot_id)
      VALUES (p_chatbot_id) RETURNING id INTO v_category_id;
    INSERT INTO public.classification_taxonomy_memberships(
      chatbot_id, taxonomy_version_id, category_id, name, definition,
      inclusion_guidance, exclusion_guidance
    ) VALUES (
      p_chatbot_id, v_version_id, v_category_id, v_name, v_definition,
      NULLIF(btrim(v_category->>'inclusionGuidance'), ''),
      NULLIF(btrim(v_category->>'exclusionGuidance'), '')
    );
  END LOOP;
  INSERT INTO public.classification_taxonomy_events(chatbot_id, taxonomy_version_id, event_type, actor_user_id)
    VALUES (p_chatbot_id, v_version_id, 'created', p_actor_user_id);
  RETURN v_version_id;
END;
$$;

CREATE FUNCTION public.approve_classification_taxonomy(
  p_chatbot_id INTEGER,
  p_version_id BIGINT,
  p_actor_user_id TEXT
)
RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE
  v_count BIGINT;
BEGIN
  PERFORM 1 FROM public.chatbots
    WHERE id = p_chatbot_id AND archived_at IS NULL FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Chatbot not found or archived'; END IF;
  PERFORM 1 FROM public.classification_taxonomy_versions
    WHERE chatbot_id = p_chatbot_id AND id = p_version_id AND state = 'draft'
    FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Only a draft taxonomy can be approved'; END IF;
  SELECT count(*) INTO v_count FROM public.classification_taxonomy_memberships
    WHERE chatbot_id = p_chatbot_id AND taxonomy_version_id = p_version_id;
  IF v_count < 1 THEN RAISE EXCEPTION 'Taxonomy must contain a category'; END IF;
  UPDATE public.classification_taxonomy_versions
    SET state = 'approved', approved_at = now(), approved_by = p_actor_user_id
    WHERE chatbot_id = p_chatbot_id AND id = p_version_id;
  INSERT INTO public.classification_taxonomy_events(chatbot_id, taxonomy_version_id, event_type, actor_user_id)
    VALUES (p_chatbot_id, p_version_id, 'approved', p_actor_user_id);
END;
$$;

CREATE TABLE public.classification_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chatbot_id INTEGER NOT NULL,
  chat_session_id INTEGER NOT NULL,
  message_id INTEGER NOT NULL,
  taxonomy_version_id BIGINT,
  operation_kind TEXT NOT NULL CHECK (operation_kind IN ('incoming', 'legacy_backfill', 'reclassification')),
  logical_operation_key TEXT NOT NULL,
  operation_identity JSONB NOT NULL CHECK (jsonb_typeof(operation_identity) = 'object'),
  payload_digest TEXT NOT NULL CHECK (payload_digest ~ '^[a-f0-9]{64}$'),
  state TEXT NOT NULL CHECK (state IN ('pending_taxonomy', 'queued', 'running', 'retryable_failed', 'succeeded', 'dead_letter', 'cancelled')),
  attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  max_attempts INTEGER NOT NULL DEFAULT 5 CHECK (max_attempts > 0),
  next_attempt_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ,
  UNIQUE (id, chatbot_id),
  UNIQUE (id, chatbot_id, message_id, taxonomy_version_id),
  UNIQUE (chatbot_id, logical_operation_key),
  FOREIGN KEY (chat_session_id, chatbot_id)
    REFERENCES public.chat_sessions(id, chatbot_id) ON DELETE RESTRICT,
  FOREIGN KEY (message_id, chat_session_id)
    REFERENCES public.messages(id, chat_session_id) ON DELETE RESTRICT,
  FOREIGN KEY (chatbot_id, taxonomy_version_id)
    REFERENCES public.classification_taxonomy_versions(chatbot_id, id) ON DELETE RESTRICT,
  CHECK (attempt_count <= max_attempts),
  CHECK ((state = 'pending_taxonomy') = (taxonomy_version_id IS NULL)),
  CHECK ((state IN ('succeeded', 'dead_letter', 'cancelled')) = (completed_at IS NOT NULL))
);

CREATE UNIQUE INDEX classification_one_incoming_run_per_message_uq
  ON public.classification_runs(chatbot_id, message_id)
  WHERE operation_kind = 'incoming';

CREATE INDEX classification_runs_claim_idx
  ON public.classification_runs(state, next_attempt_at, created_at, id);

CREATE INDEX classification_runs_message_idx
  ON public.classification_runs(chatbot_id, message_id, taxonomy_version_id);

CREATE FUNCTION public.classification_guard_run_update()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.id, NEW.chatbot_id, NEW.chat_session_id, NEW.message_id,
      NEW.operation_kind, NEW.logical_operation_key, NEW.operation_identity,
      NEW.payload_digest, NEW.max_attempts, NEW.created_at)
     IS DISTINCT FROM
     (OLD.id, OLD.chatbot_id, OLD.chat_session_id, OLD.message_id,
      OLD.operation_kind, OLD.logical_operation_key, OLD.operation_identity,
      OLD.payload_digest, OLD.max_attempts, OLD.created_at) THEN
    RAISE EXCEPTION 'Classification run identity is immutable';
  END IF;
  IF NEW.taxonomy_version_id IS DISTINCT FROM OLD.taxonomy_version_id
     AND NOT (OLD.state = 'pending_taxonomy' AND NEW.state = 'queued'
              AND OLD.taxonomy_version_id IS NULL AND NEW.taxonomy_version_id IS NOT NULL) THEN
    RAISE EXCEPTION 'A run may bind to a taxonomy version exactly once';
  END IF;
  IF NEW.taxonomy_version_id IS DISTINCT FROM OLD.taxonomy_version_id
     AND NOT EXISTS (
       SELECT 1 FROM public.classification_taxonomy_versions tv
       WHERE tv.chatbot_id = NEW.chatbot_id
         AND tv.id = NEW.taxonomy_version_id AND tv.state = 'active'
     ) THEN
    RAISE EXCEPTION 'Pending run may bind only to the active taxonomy';
  END IF;
  IF NEW.state IS DISTINCT FROM OLD.state AND NOT (
    (OLD.state = 'pending_taxonomy' AND NEW.state = 'queued')
    OR (OLD.state IN ('queued', 'retryable_failed', 'running') AND NEW.state = 'running')
    OR (OLD.state = 'running' AND NEW.state IN ('retryable_failed', 'succeeded', 'dead_letter'))
    OR (OLD.state IN ('queued', 'retryable_failed') AND NEW.state = 'dead_letter'
        AND OLD.attempt_count >= OLD.max_attempts)
  ) THEN
    RAISE EXCEPTION 'Invalid classification run transition';
  END IF;
  IF NEW.attempt_count <> OLD.attempt_count
     AND NOT (NEW.state = 'running' AND NEW.attempt_count = OLD.attempt_count + 1) THEN
    RAISE EXCEPTION 'Attempt count may increase only when a lease is claimed';
  END IF;
  IF OLD.state IN ('succeeded', 'dead_letter', 'cancelled') THEN
    RAISE EXCEPTION 'Terminal classification runs are immutable';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER classification_run_update_guard
  BEFORE UPDATE ON public.classification_runs
  FOR EACH ROW EXECUTE FUNCTION public.classification_guard_run_update();

-- The natural operation key makes enqueue and reconciliation converge. Client
-- keys are aliases and can differ while still pointing at the same run.
CREATE FUNCTION public.enqueue_classification_run(
  p_chatbot_id INTEGER,
  p_session_id INTEGER,
  p_message_id INTEGER,
  p_operation_kind TEXT,
  p_logical_operation_key TEXT,
  p_idempotency_key TEXT,
  p_operation_identity JSONB,
  p_payload_digest TEXT
)
RETURNS TABLE(run_id BIGINT, run_state TEXT, taxonomy_version_id BIGINT, created BOOLEAN)
LANGUAGE plpgsql AS $$
DECLARE
  v_run public.classification_runs%ROWTYPE;
  v_prior_run_id BIGINT;
  v_prior_identity JSONB;
  v_prior_digest CHAR(64);
  v_active_version_id BIGINT;
  v_created BOOLEAN := FALSE;
BEGIN
  IF p_operation_kind IS NULL
     OR p_logical_operation_key IS NULL
     OR p_idempotency_key IS NULL
     OR p_payload_digest IS NULL
     OR p_operation_identity IS NULL
     OR p_operation_kind <> 'incoming'
     OR length(btrim(p_logical_operation_key)) = 0
     OR length(btrim(p_idempotency_key)) NOT BETWEEN 1 AND 200
     OR p_payload_digest !~ '^[a-f0-9]{64}$'
     OR jsonb_typeof(p_operation_identity) <> 'object' THEN
    RAISE EXCEPTION 'Invalid classification operation identity';
  END IF;
  IF p_operation_identity->>'chatbotId' IS DISTINCT FROM p_chatbot_id::TEXT
     OR p_operation_identity->>'sessionId' IS DISTINCT FROM p_session_id::TEXT
     OR p_operation_identity->>'messageId' IS DISTINCT FROM p_message_id::TEXT
     OR p_operation_identity->>'operationKind' IS DISTINCT FROM p_operation_kind
     OR p_operation_identity->>'logicalOperationKey' IS DISTINCT FROM p_logical_operation_key
     OR p_operation_identity->>'taxonomyBinding' IS DISTINCT FROM 'first_active_version_after_enqueue' THEN
    RAISE EXCEPTION 'Operation identity does not match its relational scope';
  END IF;

  -- Shared chatbot lock serializes with activation while allowing distinct
  -- enqueues to proceed concurrently. Per-operation advisory lock converges
  -- same-message enqueue/reconciliation; collisions only serialize extra work.
  PERFORM 1 FROM public.chatbots
    WHERE id = p_chatbot_id AND archived_at IS NULL FOR SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Chatbot not found or archived'; END IF;
  PERFORM pg_advisory_xact_lock(p_chatbot_id, hashtext(p_logical_operation_key));
  PERFORM 1 FROM public.chat_sessions
    WHERE id = p_session_id AND chatbot_id = p_chatbot_id FOR KEY SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Chat session does not belong to chatbot'; END IF;
  PERFORM 1 FROM public.messages
    WHERE id = p_message_id AND chat_session_id = p_session_id AND sender = 'user'
    FOR SHARE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Classification requires a user message in the supplied session'; END IF;

  SELECT run_id, operation_identity, payload_digest
    INTO v_prior_run_id, v_prior_identity, v_prior_digest
    FROM public.classification_idempotency_records
    WHERE chatbot_id = p_chatbot_id AND idempotency_key = p_idempotency_key FOR UPDATE;
  IF FOUND THEN
    IF v_prior_identity IS DISTINCT FROM p_operation_identity
       OR v_prior_digest IS DISTINCT FROM p_payload_digest THEN
      RAISE EXCEPTION 'Idempotency key conflicts with a different operation';
    END IF;
    SELECT * INTO v_run FROM public.classification_runs WHERE id = v_prior_run_id;
    RETURN QUERY SELECT v_run.id, v_run.state, v_run.taxonomy_version_id, FALSE;
    RETURN;
  END IF;

  SELECT * INTO v_run FROM public.classification_runs
    WHERE chatbot_id = p_chatbot_id AND logical_operation_key = p_logical_operation_key
    FOR UPDATE;
  IF FOUND THEN
    IF v_run.operation_identity IS DISTINCT FROM p_operation_identity
       OR v_run.payload_digest IS DISTINCT FROM p_payload_digest
       OR v_run.message_id <> p_message_id
       OR v_run.chat_session_id <> p_session_id
       OR v_run.operation_kind <> p_operation_kind THEN
      RAISE EXCEPTION 'Logical operation key conflicts with a different operation';
    END IF;
  ELSE
    SELECT id INTO v_active_version_id
      FROM public.classification_taxonomy_versions
      WHERE chatbot_id = p_chatbot_id AND state = 'active';
    INSERT INTO public.classification_runs(
      chatbot_id, chat_session_id, message_id, taxonomy_version_id,
      operation_kind, logical_operation_key, operation_identity, payload_digest,
      state
    ) VALUES (
      p_chatbot_id, p_session_id, p_message_id, v_active_version_id,
      p_operation_kind, p_logical_operation_key, p_operation_identity, p_payload_digest,
      CASE WHEN v_active_version_id IS NULL THEN 'pending_taxonomy' ELSE 'queued' END
    ) RETURNING * INTO v_run;
    INSERT INTO public.classification_outbox(run_id, chatbot_id, state)
      VALUES (v_run.id, p_chatbot_id,
        CASE WHEN v_active_version_id IS NULL THEN 'pending_taxonomy' ELSE 'ready' END);
    v_created := TRUE;
  END IF;

  INSERT INTO public.classification_idempotency_records(
    chatbot_id, idempotency_key, run_id, operation_identity, payload_digest
  ) VALUES (p_chatbot_id, p_idempotency_key, v_run.id, p_operation_identity, p_payload_digest);
  RETURN QUERY SELECT v_run.id, v_run.state, v_run.taxonomy_version_id, v_created;
END;
$$;

CREATE TABLE public.classification_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL UNIQUE,
  chatbot_id INTEGER NOT NULL,
  state TEXT NOT NULL CHECK (state IN ('pending_taxonomy', 'ready', 'claimed', 'delivered', 'dead_letter', 'cancelled')),
  available_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  lease_expires_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  FOREIGN KEY (run_id, chatbot_id)
    REFERENCES public.classification_runs(id, chatbot_id) ON DELETE RESTRICT,
  CHECK ((state = 'claimed') = (lease_expires_at IS NOT NULL))
);

CREATE INDEX classification_outbox_claim_idx
  ON public.classification_outbox(state, available_at, id);

CREATE FUNCTION public.classification_guard_outbox_update()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF (NEW.id, NEW.run_id, NEW.chatbot_id, NEW.created_at)
     IS DISTINCT FROM (OLD.id, OLD.run_id, OLD.chatbot_id, OLD.created_at) THEN
    RAISE EXCEPTION 'Outbox identity is immutable';
  END IF;
  IF NEW.state IS DISTINCT FROM OLD.state AND NOT (
    (OLD.state = 'pending_taxonomy' AND NEW.state = 'ready')
    OR (OLD.state = 'ready' AND NEW.state = 'claimed')
    OR (OLD.state = 'claimed' AND NEW.state IN ('ready', 'delivered', 'dead_letter'))
    OR (OLD.state = 'ready' AND NEW.state = 'dead_letter')
  ) THEN
    RAISE EXCEPTION 'Invalid outbox lifecycle transition';
  END IF;
  IF OLD.state IN ('delivered', 'dead_letter', 'cancelled') THEN
    RAISE EXCEPTION 'Terminal outbox events are immutable';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER classification_outbox_update_guard
  BEFORE UPDATE ON public.classification_outbox
  FOR EACH ROW EXECUTE FUNCTION public.classification_guard_outbox_update();

CREATE TABLE public.classification_idempotency_records (
  chatbot_id INTEGER NOT NULL,
  idempotency_key TEXT NOT NULL CHECK (length(btrim(idempotency_key)) BETWEEN 1 AND 200),
  run_id BIGINT NOT NULL,
  operation_identity JSONB NOT NULL CHECK (jsonb_typeof(operation_identity) = 'object'),
  payload_digest TEXT NOT NULL CHECK (payload_digest ~ '^[a-f0-9]{64}$'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (chatbot_id, idempotency_key),
  FOREIGN KEY (run_id, chatbot_id)
    REFERENCES public.classification_runs(id, chatbot_id) ON DELETE RESTRICT
);

CREATE INDEX classification_idempotency_run_idx
  ON public.classification_idempotency_records(run_id, chatbot_id);

CREATE TABLE public.classification_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id BIGINT NOT NULL REFERENCES public.classification_runs(id) ON DELETE RESTRICT,
  attempt_number INTEGER NOT NULL CHECK (attempt_number > 0),
  state TEXT NOT NULL CHECK (state IN ('running', 'succeeded', 'failed', 'abandoned')),
  fencing_token TEXT NOT NULL CHECK (length(btrim(fencing_token)) >= 16),
  lease_expires_at TIMESTAMPTZ,
  model_version TEXT,
  prompt_version TEXT,
  started_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ,
  error_code TEXT,
  UNIQUE (run_id, attempt_number),
  CHECK ((state = 'running') = (lease_expires_at IS NOT NULL)),
