-- Additive, unexecuted migration for versioned message classification.
-- Minimum PostgreSQL version: 11 (project baseline must be verified before apply).
-- Does not change messages.enquiry_category or grant database roles/privileges.
-- Apply only after checking the live schema and confirming the composite keys below.

BEGIN;

ALTER TABLE public.chatbots
  ADD COLUMN IF NOT EXISTS archived_at TIMESTAMPTZ;

ALTER TABLE public.chat_sessions
  ADD CONSTRAINT chat_sessions_id_chatbot_uq UNIQUE (id, chatbot_id);

ALTER TABLE public.messages
  ADD CONSTRAINT messages_id_session_uq UNIQUE (id, chat_session_id);

-- Capture a high-water mark so reconciliation never treats pre-rollout
-- messages as incoming work or performs implicit historical reclassification.
CREATE TABLE public.classification_reconciliation_control (
  singleton_id SMALLINT PRIMARY KEY CHECK (singleton_id = 1),
  message_id_cutoff INTEGER NOT NULL CHECK (message_id_cutoff >= 0)
);

INSERT INTO public.classification_reconciliation_control(singleton_id, message_id_cutoff)
SELECT 1, COALESCE(max(id), 0)::INTEGER FROM public.messages;

CREATE TABLE public.classification_taxonomy_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chatbot_id INTEGER NOT NULL
    REFERENCES public.chatbots(id) ON DELETE RESTRICT,
  version_number INTEGER NOT NULL CHECK (version_number > 0),
  state TEXT NOT NULL CHECK (state IN ('draft', 'approved', 'active', 'superseded', 'archived')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  approved_at TIMESTAMPTZ,
  approved_by TEXT,
  activated_at TIMESTAMPTZ,
  UNIQUE (chatbot_id, id),
  UNIQUE (chatbot_id, version_number),
  CHECK (
    (state = 'draft' AND approved_at IS NULL AND activated_at IS NULL)
    OR (state = 'approved' AND approved_at IS NOT NULL AND activated_at IS NULL)
    OR (state IN ('active', 'superseded', 'archived')
        AND approved_at IS NOT NULL AND activated_at IS NOT NULL)
  )
);

CREATE UNIQUE INDEX classification_taxonomy_one_active_uq
  ON public.classification_taxonomy_versions(chatbot_id)
  WHERE state = 'active';

CREATE TABLE public.classification_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
