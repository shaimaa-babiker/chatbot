BEGIN;

CREATE TABLE public.chatbot_tags (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  chatbot_id INTEGER NOT NULL
    REFERENCES public.chatbots(id) ON DELETE CASCADE,
  name TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 50),
  purpose TEXT NOT NULL CHECK (length(btrim(purpose)) BETWEEN 1 AND 300),
  category TEXT NOT NULL CHECK (category IN ('product', 'service', 'opportunity')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX chatbot_tags_active_name_uq
  ON public.chatbot_tags (chatbot_id, lower(name))
  WHERE is_active;

CREATE TABLE public.message_tags (
  message_id INTEGER NOT NULL
    REFERENCES public.messages(id) ON DELETE CASCADE,
  tag_id INTEGER NOT NULL
    REFERENCES public.chatbot_tags(id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (message_id, tag_id)
);

CREATE INDEX message_tags_tag_id_idx ON public.message_tags(tag_id);

COMMIT;
